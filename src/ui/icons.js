/**
 * Renders a crisp monochrome SVG icon inheriting `currentColor`.
 * @param {keyof typeof ICON_PATHS} name
 * @param {number} [size=15]
 * @param {string} [extraClass='']
 * @returns {string}
 */
export function svgIcon(name, size = 15, extraClass = '') {
  const inner = ICON_PATHS[name] || ICON_PATHS.sparkles;
  const cls = `ui-svg-icon ${extraClass}`.trim();
  return `<svg class="${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.85" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
}

/**
 * Renders a geometric army color indicator dot (replacing OS circle emojis `⚪`, `🔴`, `🟢`, `⚫`).
 * @param {'white' | 'red' | 'green'} color
 * @param {'tricolore' | 'wood'} [boardTheme='tricolore']
 * @returns {string}
 */
export function armyDotHtml(color, boardTheme = 'tricolore') {
  const variant =
    color === 'white'
      ? 'white'
      : color === 'red'
        ? 'red'
        : boardTheme === 'wood'
          ? 'ebony'
          : 'green';
  return `<span class="army-dot army-dot--${variant}" aria-hidden="true"></span>`;
}
